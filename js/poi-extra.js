(function applyPoiExtra() {
  if (!window.SONG_POIS || !window.POI_EXTRA) return;
  Object.keys(SONG_POIS).forEach(function (city) {
    (SONG_POIS[city].pois || []).forEach(function (p) {
      var e = POI_EXTRA[p.id];
      if (!e) return;
      if (e.intro) p.intro = e.intro;
      if (e.guide) p.guide = e.guide;
      if (e.culture) p.culture = e.culture;
      if (e.travel) p.travel = e.travel;
    });
  });
})();
